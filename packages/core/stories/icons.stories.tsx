const groupStory = (name: string, names: IconName[]): Story => ({
  name,
  render: (_, { speak }) => (
    <IconGrid
      icons={icons.filter(({ componentName }) =>
        names.includes(componentName as IconName),
      )}
      speak={speak}
    />
  ),
  parameters,
});

